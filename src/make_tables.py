"""Builds every table of the paper from results/*.csv (no number is typed by hand).

Writes results/tables.md (for checking) and results/tables.tex (IEEE booktabs).
"""
import json

import pandas as pd

from common import RESULTS

ML_ORDER = ["Logistic Regression", "Decision Tree", "Random Forest", "AdaBoost",
            "SVM (RBF)", "KNN (k=5)", "XGBoost"]


def pm(mean, std, scale=100, nd=2):
    return f"{mean * scale:.{nd}f} $\\pm$ {std * scale:.{nd}f}"


def pct(x, nd=2):
    return f"{x * 100:.{nd}f}"


md, tex = [], []
PAPER_TABLES = RESULTS.parent / "paper" / "tables"
PAPER_TABLES.mkdir(parents=True, exist_ok=True)


def emit(title, df, label, wide=False):
    """Markdown copy for checking + one LaTeX file per table for the paper."""
    md.append(f"## {title}\n\n" + df.to_markdown(index=False) + "\n")
    cols = "l" + "r" * (df.shape[1] - 1)
    ltx = df.copy()
    ltx.columns = [c.replace("%", "\\%") for c in ltx.columns]
    ltx = ltx.map(lambda v: v.replace("%", "\\%") if isinstance(v, str) else v)
    body = ltx.to_latex(index=False, escape=False, column_format=cols)
    env, width = ("table*", "\\textwidth") if wide else ("table", "\\columnwidth")
    block = (f"% generated by src/make_tables.py from results/*.csv -- do not edit by hand\n"
             f"\\begin{{{env}}}[t]\n\\centering\n\\caption{{{title}}}\n\\label{{{label}}}\n"
             f"\\resizebox{{{width}}}{{!}}{{%\n{body}}}\n\\end{{{env}}}\n")
    tex.append(block)
    (PAPER_TABLES / f"{label.split(':')[1]}.tex").write_text(block)


# ---- Table: UCI, 7 ML + 1D-CNN, protocols A and B --------------------------------
e1 = pd.read_csv(RESULTS / "exp1_uci_ml_summary.csv")
e2b = pd.read_csv(RESULTS / "exp2b_uci_cnn_summary.csv")
uci = pd.concat([e1, e2b], ignore_index=True)
rows = []
for model in ML_ORDER + ["1D-CNN (features, after [7])"]:
    a = uci[(uci.model == model) & uci.protocol.str.startswith("A")].iloc[0]
    b = uci[(uci.model == model) & uci.protocol.str.startswith("B")].iloc[0]
    rows.append({"Model": model.replace(" (features, after [7])", " [7]"),
                 "Acc. A (%)": pm(a.accuracy_mean, a.accuracy_std),
                 "Acc. B (%)": pm(b.accuracy_mean, b.accuracy_std),
                 "$\\Delta$ (pp)": f"{(b.accuracy_mean - a.accuracy_mean) * 100:+.2f}",
                 "F1 B (%)": pct(b.f1_mean), "MCC B": f"{b.mcc_mean:.3f}",
                 "Train B (s)": f"{b.fit_s_mean:.2f}"})
emit("UCI Phishing Websites, 10-fold CV. A: all 11,055 rows (protocol of [3]); "
     "B: 5,849 unique rows. Mean $\\pm$ std over folds.", pd.DataFrame(rows), "tab:uci", wide=True)

# ---- Table: URLs (Ebbu2017), 7 ML + 3 DL ------------------------------------------
e2 = pd.read_csv(RESULTS / "exp2_urls_summary.csv")
runs2 = pd.read_csv(RESULTS / "exp2_urls_runs.csv")
n_seeds = runs2.seed.nunique()
# seed 42 shared the CPU with experiment 2b, so its wall-clock training times are
# not comparable; training time is averaged over the seeds that ran alone.
train_clean = runs2[runs2.seed != 42].groupby("model").train_s.mean()
rows = []
for _, r in e2.iterrows():
    rows.append({"Model": r.model, "Type": r.family,
                 "Acc. (%)": pm(r.accuracy_mean, r.accuracy_std),
                 "Prec. (%)": pct(r.precision_mean), "Rec. (%)": pct(r.recall_mean),
                 "F1 (%)": pm(r.f1_mean, r.f1_std), "FPR (%)": pct(r.fpr_mean),
                 "PR-AUC": f"{r.pr_auc_mean:.4f}", "Train (s)": f"{train_clean[r.model]:.1f}"})
emit(f"Ebbu2017 URLs (54,634 unique), stratified 80/20 split, mean $\\pm$ std over {n_seeds} seeds. "
     "ML: 20 lexical features; DL: raw characters.", pd.DataFrame(rows), "tab:urls", wide=True)

# ---- Table: imbalance ----------------------------------------------------------------
e3 = pd.read_csv(RESULTS / "exp3_imbalance.csv")
keep = ["Random Forest", "XGBoost", "CNN (char)", "CNN+LSTM (char)"]
rows = []
for model in keep:
    for target in ["full", "0.1", "0.02", "0.01"]:
        r = e3[(e3.model == model) & (e3.target.astype(str) == target)].iloc[0]
        rows.append({"Model": model, "Phishing share": f"{r.prevalence * 100:.1f}%",
                     "Acc. (%)": pct(r.accuracy), "Prec. (%)": pct(r.precision),
                     "Prec. formula (%)": pct(r.precision_analytic), "Rec. (%)": pct(r.recall),
                     "F1 (%)": pct(r.f1), "MCC": f"{r.mcc:.3f}", "PR-AUC": f"{r.pr_auc:.3f}"})
emit("Same models at lower phishing prevalence (all legitimate test URLs kept, phishing "
     "sub-sampled; mean of 50 draws $\\times$ seeds). Threshold fixed at 0.5.",
     pd.DataFrame(rows), "tab:imbalance", wide=True)

# ---- Table: latency ----------------------------------------------------------------
e4 = pd.read_csv(RESULTS / "exp4_latency.csv")
acc = e2.set_index("model")["f1_mean"]
rows = [{"Model": r.model, "F1 (%)": pct(acc[r.model]),
         "Median (ms)": f"{r.latency_median_ms:.3f}", "p95 (ms)": f"{r.latency_p95_ms:.3f}",
         "Batched (ms/URL)": f"{r.batched_ms_per_url:.3f}", "Size (MB)": f"{r.model_size_mb:.3f}",
         "RAM incr. (MB)": f"{r.memory_increment_mb:.1f}"} for r in e4.itertuples()]
emit("End-to-end single-URL inference on CPU (1 thread, batch 1, 1,000 URLs after 50 warm-up "
     "calls), model size on disk and peak RSS increment.", pd.DataFrame(rows), "tab:latency", wide=True)

# ---- Table: cascade ------------------------------------------------------------------
e5 = pd.read_csv(RESULTS / "exp5_cascade.csv")
tier2 = pd.read_csv(RESULTS / "exp5_cascade_runs.csv").tier2.iloc[0]
rows = [{"$\\delta$": f"{r.delta:.1f}", "Escalated (%)": pct(r.escalation_rate_mean),
         "Acc. (%)": pct(r.accuracy_mean), "F1 (%)": pct(r.f1_mean), "FPR (%)": pct(r.fpr_mean),
         "Mean latency (ms)": f"{r.expected_latency_ms_mean:.3f}"} for r in e5.itertuples()]
emit(f"Two-tier cascade: XGBoost, escalating to {tier2} when $|p-0.5|<\\delta$ "
     "($\\delta$=0: XGBoost only; 0.5: DL only).", pd.DataFrame(rows), "tab:cascade")

info = json.load(open(RESULTS / "exp2_dataset_info.json"))
md.append("## Environment\n\n```json\n" + json.dumps(info["environment"], indent=2) + "\n```\n")
(RESULTS / "tables.md").write_text("\n".join(md))
(RESULTS / "tables.tex").write_text("\n".join(tex))
print("\n".join(md))
